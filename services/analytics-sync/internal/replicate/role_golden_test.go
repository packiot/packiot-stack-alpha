func roleMigrationSQL(t *testing.T) string {
	t.Helper()
	_, here, _, _ := runtime.Caller(0)
	b, err := os.ReadFile(filepath.Join(filepath.Dir(here), roleMigration))
	if err != nil {
		t.Fatalf("read migration: %v", err)
	}
	var out []string
	for _, l := range strings.Split(string(b), "\n") {
		if !strings.HasPrefix(strings.TrimSpace(l), `\`) { // psql meta-commands
			out = append(out, l)
		}
	}
	return strings.Join(out, "\n")
}

type roleGolden struct {
	ctx   context.Context
	admin *pgxpool.Pool // superuser: fixture + the LEGACY side (public.*)
	role  *pgxpool.Pool // legacy_replicator through internal/db.NewPool, stamped app.tenant_id=3
	// the same login WITHOUT the stamp: must see no tenant rows (fails closed)
	unstamped *pgxpool.Pool
	log       *slog.Logger
}

func newRoleGolden(t *testing.T) *roleGolden {
	raw := os.Getenv("DATABASE_URL")
	if raw == "" {
		t.Skip("DATABASE_URL not set")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 120*time.Second)
	t.Cleanup(cancel)
	cfg, err := pgxpool.ParseConfig(raw)
	if err != nil {
		t.Fatal(err)
	}
	cfg.ConnConfig.DefaultQueryExecMode = pgx.QueryExecModeSimpleProtocol // multi-statement bodies
	admin, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(admin.Close)

	// Start from no role (a previous run may have left it with grants).
	if _, err := admin.Exec(ctx, `DO $$ BEGIN IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='legacy_replicator') THEN
	   DROP OWNED BY legacy_replicator; END IF; END $$`); err != nil {
		t.Fatalf("pre-clean: %v", err)
	}
	if _, err := admin.Exec(ctx, `DROP ROLE IF EXISTS legacy_replicator`); err != nil {
		t.Fatalf("pre-clean role: %v", err)
	}
	if _, err := admin.Exec(ctx, roleFixtureDDL); err != nil {
		t.Fatalf("fixture: %v", err)
	}
	up := roleMigrationSQL(t)
	for i := 0; i < 2; i++ { // idempotent
		if _, err := admin.Exec(ctx, up); err != nil {
			t.Fatalf("01-up.sql (run %d): %v", i+1, err)
		}
	}
	u, _ := url.Parse(raw)
	dbName := strings.TrimPrefix(u.Path, "/")
	// staging sets this search_path at the DATABASE level (the code's unqualified packml_register /
	// equipments / production_orders resolve through it); scoped to the role here so the module's other
	// golden tests keep their own path.
	for _, q := range []string{
		`ALTER ROLE legacy_replicator PASSWORD '` + roleGoldenPassword + `'`,
		`ALTER ROLE legacy_replicator IN DATABASE "` + dbName + `" SET search_path = gold, silver, ops, serving, core, public`,
	} {
		if _, err := admin.Exec(ctx, q); err != nil {
			t.Fatalf("%s: %v", q, err)
		}
	}
	port := 5432
	if p := u.Port(); p != "" {
		port, _ = strconv.Atoi(p)
	}
	logger := slog.New(slog.NewTextHandler(io.Discard, nil))
	open := func(params map[string]string) *pgxpool.Pool {
		p, err := db.NewPool(ctx, &db.DBCreds{Host: u.Hostname(), Port: port, User: DestRole, Password: roleGoldenPassword,
			Params: params}, dbName, "legacy-replicator-golden", logger)
		if err != nil {
			t.Fatalf("db.NewPool as legacy_replicator: %v", err)
		}
		t.Cleanup(p.Close)
		return p
	}
	// exactly what cmd/legacy-replicator does: the tenant stamp in the startup packet
	role := open(map[string]string{"app.tenant_id": "3"})
	return &roleGolden{ctx: ctx, admin: admin, role: role, unstamped: open(nil), log: logger}
}

