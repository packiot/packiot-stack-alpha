const schemaSQL = `
CREATE EXTENSION IF NOT EXISTS timescaledb;
CREATE SCHEMA core; CREATE SCHEMA silver; CREATE SCHEMA bronze; CREATE SCHEMA gold; CREATE SCHEMA serving; CREATE SCHEMA ops;
CREATE FUNCTION public.current_tenant() RETURNS int LANGUAGE sql STABLE AS
  $$ SELECT nullif(current_setting('app.tenant_id', true), '')::int $$;
CREATE TABLE core.enterprises (id_enterprise int PRIMARY KEY, nm_enterprise text, api_key text, updated_at timestamptz);
CREATE FUNCTION public.set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN NEW.updated_at := now(); RETURN NEW; END $$;
CREATE TRIGGER trg_set_updated_at BEFORE UPDATE ON core.enterprises FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TABLE core.equipments (id_equipment int PRIMARY KEY, id_enterprise int NOT NULL REFERENCES core.enterprises,
  nm_equipment text, tp_equipment int, lead_machine int REFERENCES core.equipments(id_equipment));
ALTER TABLE core.equipments ENABLE ROW LEVEL SECURITY; ALTER TABLE core.equipments FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant ON core.equipments USING (id_enterprise = public.current_tenant());
CREATE TABLE core.production_orders (id_production_order bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_enterprise int NOT NULL, id_equipment int REFERENCES core.equipments, order_number text, status int, ts_creation timestamptz);
CREATE TABLE silver.equipment_events (id_equipment int NOT NULL, ts_event timestamptz NOT NULL, status int,
  cd_category text, ts_end timestamptz, PRIMARY KEY (id_equipment, ts_event));
SELECT create_hypertable('silver.equipment_events', 'ts_event', chunk_time_interval => interval '7 days');
CREATE TABLE bronze.box_scans (box_scan_id bigint PRIMARY KEY, id_enterprise int NOT NULL, qty int, ts_value timestamptz,
  voids_box_scan_id bigint REFERENCES bronze.box_scans);
CREATE FUNCTION public.box_scans_no_mutate() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'append-only'; END $$;
CREATE TRIGGER trg_box_scans_no_mutate BEFORE UPDATE OR DELETE ON bronze.box_scans FOR EACH ROW EXECUTE FUNCTION box_scans_no_mutate();
CREATE TABLE gold.equipment_oee_shift_weekly (id_equipment int, ts_value timestamptz, oee float8);
CREATE TABLE serving.refresh_log (from_ts timestamptz, to_ts timestamptz, tenant int);
CREATE FUNCTION serving.refresh_downtime_events_resolved(f timestamptz, t timestamptz) RETURNS void LANGUAGE sql SECURITY DEFINER AS
  $$ INSERT INTO serving.refresh_log VALUES (f, t, public.current_tenant()) $$;
CREATE TABLE ops.data_invariant_result (run_at timestamptz NOT NULL, check_id text NOT NULL, dimension text NOT NULL,
  layer text NOT NULL, severity text NOT NULL, id_enterprise int, observed numeric, expected text, ok boolean NOT NULL,
  detail text, source text NOT NULL DEFAULT 'db');
`

// migrationSQL is the real db/migrations/t-prod-reflector-roles/01-up.sql (psql meta-commands stripped): the
// fixture runs the reflector AS the roles the migration creates, so a missing grant fails here.
func migrationSQL(t *testing.T) string {
	t.Helper()
	b, err := os.ReadFile("../../../../db/migrations/t-prod-reflector-roles/01-up.sql")
	if err != nil {
		t.Fatal(err)
	}
	var out []string
	for _, l := range strings.Split(string(b), "\n") {
		if !strings.HasPrefix(strings.TrimSpace(l), "\\") {
			out = append(out, l)
		}
	}
	return strings.Join(out, "\n")
}

type fixture struct {
	admin    map[string]*pgx.Conn // "src" / "dst" as postgres
	srcPool  *pgxpool.Pool
	dstPool  *pgxpool.Pool
	cfg      *Config
	m        *Metrics
	log      *slog.Logger
	baseURL  *url.URL
	srcDB    string
	dstDB    string
	roleSrc  string
	roleDst  string
	password string
}

type testWriter struct{ t *testing.T }

func (w testWriter) Write(b []byte) (int, error) { w.t.Log(string(b)); return len(b), nil }

func mustExec(t *testing.T, c *pgx.Conn, sql string, args ...any) {
	t.Helper()
	if _, err := c.Exec(context.Background(), sql, args...); err != nil {
		t.Fatalf("%s: %v", sql, err)
	}
}

func dbURL(base *url.URL, db, user, pw string) string {
	u := *base
	u.Path = "/" + db
	u.User = url.UserPassword(user, pw)
	return u.String()
}

func setup(t *testing.T) *fixture {
	t.Helper()
	raw := os.Getenv("DATABASE_URL")
	if raw == "" {
		t.Skip("DATABASE_URL not set")
	}
	ctx := context.Background()
	base, err := url.Parse(raw)
	if err != nil {
		t.Fatal(err)
	}
	f := &fixture{admin: map[string]*pgx.Conn{}, baseURL: base, srcDB: "mirror_prod", dstDB: "mirror_staging",
		roleSrc: SrcRole, roleDst: DstRole, password: "golden-mirror"}
	root, err := pgx.Connect(ctx, raw)
	if err != nil {
		t.Fatal(err)
	}
	defer root.Close(ctx)
	for _, db := range []string{f.srcDB, f.dstDB} {
		mustExec(t, root, "DROP DATABASE IF EXISTS "+db+" WITH (FORCE)")
		mustExec(t, root, "CREATE DATABASE "+db)
	}
	adminPW, _ := base.User.Password()
	defer func() {
		for _, r := range []string{f.roleSrc, f.roleDst} {
			mustExec(t, root, fmt.Sprintf("ALTER ROLE %s PASSWORD '%s'", r, f.password))
		}
	}()
	for side, db := range map[string]string{"src": f.srcDB, "dst": f.dstDB} {
		c, err := pgx.Connect(ctx, dbURL(base, db, base.User.Username(), adminPW))
		if err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { c.Close(context.Background()) })
		mustExec(t, c, schemaSQL)
		mustExec(t, c, migrationSQL(t))
		f.admin[side] = c
	}
	f.cfg = &Config{Interval: time.Minute, LookbackDays: 35, MaxDeletes: 100, NameSuffix: " (mirror)",
		IDBlock: 1_000_000_000, StatementTimeout: time.Minute, MaxLag: 10 * time.Minute}
	f.m = NewMetrics()
	f.log = slog.New(slog.NewTextHandler(testWriter{t}, nil))
	f.srcPool = f.pool(t, f.srcDB, f.roleSrc, map[string]string{"app.tenant_id": "5", "TimeZone": "UTC",
		"default_transaction_read_only": "on"})
	f.dstPool = f.pool(t, f.dstDB, f.roleDst, map[string]string{"app.tenant_id": "5", "TimeZone": "UTC"})
	return f
}

func (f *fixture) pool(t *testing.T, db, role string, params map[string]string) *pgxpool.Pool {
	t.Helper()
	pc, err := pgxpool.ParseConfig(dbURL(f.baseURL, db, role, f.password))
	if err != nil {
		t.Fatal(err)
	}
	pc.ConnConfig.DefaultQueryExecMode = pgx.QueryExecModeSimpleProtocol // as in production (internal/db)
	for k, v := range params {
		pc.ConnConfig.RuntimeParams[k] = v
	}
	p, err := pgxpool.NewWithConfig(context.Background(), pc)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(p.Close)
	return p
}

func scalar[T any](t *testing.T, c *pgx.Conn, sql string) T {
	t.Helper()
	var v T
	if err := c.QueryRow(context.Background(), sql).Scan(&v); err != nil {
		t.Fatalf("%s: %v", sql, err)
	}
	return v
}

// seed: production = the truth after go-live; staging = the go-live copy, then drifted.
func (f *fixture) seed(t *testing.T) {
	src, dst := f.admin["src"], f.admin["dst"]
	base := time.Now().UTC().Truncate(time.Hour) // one instant for both databases (now() differs per server call)
	for _, c := range []*pgx.Conn{src, dst} {
		mustExec(t, c, `INSERT INTO core.enterprises VALUES (5, 'Bispharma', 'KEY', now()), (3, 'CPACK-Staging', 'K3', now())`)
		mustExec(t, c, `INSERT INTO core.equipments SELECT g, 5, 'M' || g, 1, NULL FROM generate_series(1, 12) g`)
		mustExec(t, c, `INSERT INTO core.equipments VALUES (300, 3, 'CPACK L1', 3, NULL)`)
		mustExec(t, c, `INSERT INTO silver.equipment_events VALUES (1, $1::timestamptz - interval '2 days', 6, NULL, NULL),
		                                                          (2, $1::timestamptz - interval '1 day', 6, NULL, NULL),
		                                                          (300, $1::timestamptz - interval '1 day', 6, 'cpack', NULL)`, base)
		mustExec(t, c, `INSERT INTO bronze.box_scans VALUES (1, 5, 10, $1::timestamptz - interval '1 hour', NULL)`, base)
		mustExec(t, c, `INSERT INTO gold.equipment_oee_shift_weekly VALUES (1, date_trunc('day', $1::timestamptz), 0.5)`, base)
	}
	// production after go-live: prod key rotated; a new line (id in the production block) led by a NEW machine with
	// a higher id (self-FK order); a PO; an event justified; a new scan; a recomputed weekly row; M12 deleted.
	mustExec(t, src, `UPDATE core.enterprises SET api_key = 'PROD-KEY' WHERE id_enterprise = 5`)
	mustExec(t, src, `INSERT INTO core.equipments VALUES (1000000002, 5, 'M-new', 1, NULL)`)
	mustExec(t, src, `INSERT INTO core.equipments VALUES (1000000001, 5, 'L-new', 3, 1000000002)`)
	mustExec(t, src, `DELETE FROM core.equipments WHERE id_equipment = 12`)
	mustExec(t, src, `INSERT INTO core.production_orders VALUES (1000000001, 5, 1000000001, 'PO-A', 2, now())`)
	mustExec(t, src, `UPDATE silver.equipment_events SET cd_category = 'setup', ts_end = ts_event + interval '5 min' WHERE id_equipment = 1`)
	mustExec(t, src, `INSERT INTO bronze.box_scans VALUES (1000000001, 5, 12, now(), NULL)`)
	mustExec(t, src, `UPDATE gold.equipment_oee_shift_weekly SET oee = 0.61`)
	// staging drift: a stray write and a row staging minted itself
	mustExec(t, dst, `UPDATE core.equipments SET nm_equipment = 'edited on staging' WHERE id_equipment = 3`)
	mustExec(t, dst, `INSERT INTO silver.equipment_events VALUES (2, now() - interval '3 hours', 6, NULL, NULL)`)
	// staging's other tenant changes nothing
}

func TestGoldenReflectConverges(t *testing.T) {
	f := setup(t)
	f.seed(t)
	ctx := context.Background()
	src, dst := f.admin["src"], f.admin["dst"]
	r := NewReflector(f.cfg, 5, f.srcPool, f.dstPool, f.m, f.log)

	res, err := r.Pass(ctx, true)
	if err != nil {
		t.Fatal(err)
	}
	if !res.Converged || res.Errors != 0 || res.Unconverged != 0 {
		t.Fatalf("pass did not converge: %+v", res)
	}
	// every reflected table equal for tenant 5
	for _, q := range []string{
		`SELECT md5(string_agg(x::text, ',' ORDER BY x::text)) FROM (SELECT id_equipment, id_enterprise, nm_equipment, tp_equipment, lead_machine FROM core.equipments WHERE id_enterprise = 5) x`,
		`SELECT md5(string_agg(x::text, ',' ORDER BY x::text)) FROM (SELECT * FROM core.production_orders WHERE id_enterprise = 5) x`,
		`SELECT md5(string_agg(x::text, ',' ORDER BY x::text)) FROM (SELECT * FROM silver.equipment_events WHERE id_equipment < 1000 AND id_equipment <> 300 OR id_equipment > 999999999) x`,
		`SELECT md5(string_agg(x::text, ',' ORDER BY x::text)) FROM (SELECT * FROM bronze.box_scans) x`,
		`SELECT md5(string_agg(x::text, ',' ORDER BY x::text)) FROM (SELECT * FROM gold.equipment_oee_shift_weekly) x`,
	} {
		if a, b := scalar[string](t, src, q), scalar[string](t, dst, q); a != b {
			t.Fatalf("not equal after the pass: %s", q)
		}
	}
	if v := scalar[int](t, dst, `SELECT lead_machine FROM core.equipments WHERE id_equipment = 1000000001`); v != 1000000002 {
		t.Fatalf("self reference not set: %d", v)
	}
	if v := scalar[string](t, dst, `SELECT api_key FROM core.enterprises WHERE id_enterprise = 5`); v != "KEY" {
		t.Fatalf("staging's api key must never be overwritten, got %q", v)
	}
	if v := scalar[string](t, dst, `SELECT nm_enterprise FROM core.enterprises WHERE id_enterprise = 5`); v != "Bispharma (mirror)" {
		t.Fatalf("name = %q", v)
	}
	// the other tenant is untouched
	if v := scalar[string](t, dst, `SELECT cd_category FROM silver.equipment_events WHERE id_equipment = 300`); v != "cpack" {
		t.Fatal("tenant 3 row changed")
	}
	if v := scalar[string](t, dst, `SELECT nm_enterprise FROM core.enterprises WHERE id_enterprise = 3`); v != "CPACK-Staging" {
		t.Fatal("tenant 3 enterprise changed")
	}
	// serving re-resolved the changed event days, stamped with tenant 5
	if v := scalar[int](t, dst, `SELECT count(*) FROM serving.refresh_log WHERE tenant = 5`); v != 1 {
		t.Fatalf("serving refresh calls = %d", v)
	}

	// second pass: nothing to do
	res, err = r.Pass(ctx, false)
	if err != nil || res.Changed != 0 || !res.Converged {
		t.Fatalf("idempotent pass: %+v %v", res, err)
	}

	// a write on staging behind the reflector's back is undone AND counted as a staging write
	mustExec(t, dst, `UPDATE core.equipments SET nm_equipment = 'again' WHERE id_equipment = 3`)
	res, err = r.Pass(ctx, false)
	if err != nil || res.StagingWrites != 1 || !res.Converged {
		t.Fatalf("staging write: %+v %v", res, err)
	}

	// append-only: a differing scan on staging is reported, never mutated (the trigger would refuse anyway)
	mustExec(t, dst, `ALTER TABLE bronze.box_scans DISABLE TRIGGER trg_box_scans_no_mutate`)
	mustExec(t, dst, `UPDATE bronze.box_scans SET qty = 99 WHERE box_scan_id = 1`)
	mustExec(t, dst, `ALTER TABLE bronze.box_scans ENABLE TRIGGER trg_box_scans_no_mutate`)
	res, err = r.Pass(ctx, false)
	if err != nil || res.Divergent != 1 || res.Errors != 0 {
		t.Fatalf("append-only: %+v %v", res, err)
	}

	// invariants: config/POs equal; production sequences below the block → MR4 fails; after the floor it passes
	r.lastConverged = time.Now()
	inv, err := r.Invariants(ctx)
	if err != nil {
		t.Fatal(err)
	}
	byID := map[string]Invariant{}
	for _, i := range inv {
		byID[i.CheckID] = i
	}
	if !byID["MR1_prod_mirror_config"].OK || !byID["MR2_prod_mirror_pos"].OK || !byID["MR3_prod_mirror_lag"].OK {
		t.Fatalf("invariants: %+v", inv)
	}
	if byID["MR4_prod_id_block"].OK {
		t.Fatal("production's PO sequence is below the block: MR4 must fail")
	}
	mustExec(t, src, `SELECT setval(pg_get_serial_sequence('core.production_orders', 'id_production_order'), 1000000001)`)
	inv, _ = r.Invariants(ctx)
	for _, i := range inv {
		if i.CheckID == "MR4_prod_id_block" && !i.OK {
			t.Fatalf("MR4 after the floor: %+v", i)
		}
	}
	if err := r.RecordInvariants(ctx, inv); err != nil {
		t.Fatal(err)
	}
	if v := scalar[int](t, dst, `SELECT count(*) FROM ops.data_invariant_result WHERE source = 'prod-reflector' AND id_enterprise = 5`); v != len(inv) {
		t.Fatalf("recorded %d", v)
	}
}

func TestGoldenGuardsAndDryRun(t *testing.T) {
	f := setup(t)
	f.seed(t)
	ctx := context.Background()
	dst := f.admin["dst"]
	before := scalar[string](t, dst, `SELECT md5(string_agg(x::text, ',' ORDER BY x::text)) FROM core.equipments x`)

	// dry run: the whole pass runs, then rolls back
	dry := *f.cfg
	dry.DryRun = true
	r := NewReflector(&dry, 5, f.srcPool, f.dstPool, f.m, f.log)
	res, err := r.Pass(ctx, true)
	if err != nil || res.Converged || res.Upserts == 0 {
		t.Fatalf("dry run: %+v %v", res, err)
	}
	if after := scalar[string](t, dst, `SELECT md5(string_agg(x::text, ',' ORDER BY x::text)) FROM core.equipments x`); after != before {
		t.Fatal("dry run wrote to staging")
	}

	// a production connection WITHOUT the tenant stamp sees no equipment (FORCE RLS): it must not empty staging
	unstamped := f.pool(t, f.srcDB, f.roleSrc, map[string]string{"TimeZone": "UTC", "default_transaction_read_only": "on"})
	r = NewReflector(f.cfg, 5, unstamped, f.dstPool, f.m, f.log)
	res, err = r.Pass(ctx, true)
	if err != nil {
		t.Fatal(err)
	}
	if res.Guarded == 0 || res.Converged {
		t.Fatalf("empty-source guard did not trip: %+v", res)
	}
	if v := scalar[int](t, dst, `SELECT count(*) FROM core.equipments WHERE id_enterprise = 5`); v < 12 {
		t.Fatalf("staging equipment deleted on an empty source: %d left", v)
	}

	// production without the enterprise row: refuse the pass outright
	mustExec(t, f.admin["src"], `ALTER TABLE bronze.box_scans DISABLE TRIGGER trg_box_scans_no_mutate;
	  DELETE FROM core.production_orders; DELETE FROM core.equipments WHERE id_enterprise = 5;
	  DELETE FROM bronze.box_scans; DELETE FROM core.enterprises WHERE id_enterprise = 5`)
	r = NewReflector(f.cfg, 5, f.srcPool, f.dstPool, f.m, f.log)
	if _, err := r.Pass(ctx, true); err == nil {
		t.Fatal("a pass against a production without the enterprise must fail")
	}
}
