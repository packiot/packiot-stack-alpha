// Golden fixture: two real databases on the CI Postgres (TimescaleDB 2.27 / PG 15) stand in for production and
// staging. Both get the same minimal schema (the shapes that matter: FORCE RLS keyed on app.tenant_id, a
// self-referencing FK, a hypertable with a natural key, an append-only trigger, a table without a primary key,
// a serving refresh, an identity column) and least-privilege roles like db/migrations/t-prod-reflector-roles.
//
//   DATABASE_URL=postgres://postgres:golden@localhost:5432/golden?sslmode=disable go test -tags golden ./internal/mirror/

