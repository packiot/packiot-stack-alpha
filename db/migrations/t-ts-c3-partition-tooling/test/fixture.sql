\set ON_ERROR_STOP 1
CREATE SCHEMA silver; CREATE SCHEMA bronze; CREATE SCHEMA ops;
CREATE ROLE readapi_ro; CREATE ROLE tenant_reader LOGIN;
-- a least-privilege WRITER like stream_engine: may write the tables, has no grant on anything the tooling creates
CREATE ROLE lp_writer LOGIN;
CREATE FUNCTION current_tenant() RETURNS int LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('app.tenant_id', true), '')::int $$;
CREATE TABLE ops.retention_policy (relation text PRIMARY KEY, kind text NOT NULL CHECK (kind IN ('hypertable','cagg','plain')), time_expr text, keep interval, updated_at timestamptz);
CREATE SEQUENCE silver.ev_source_seq;
-- events-like: identity, two identical unique indexes, a sequence default, compression
CREATE TABLE silver.equipment_events (id_equipment_event bigint GENERATED BY DEFAULT AS IDENTITY, id_equipment int NOT NULL,
  ts_event timestamptz NOT NULL, ts_end timestamptz, status int, source_seq bigint DEFAULT nextval('silver.ev_source_seq'));
CREATE UNIQUE INDEX equipment_events_pk ON silver.equipment_events (id_equipment, ts_event);
CREATE UNIQUE INDEX equipment_events_pkey ON silver.equipment_events (id_equipment, ts_event);
ALTER SEQUENCE silver.ev_source_seq OWNED BY silver.equipment_events.source_seq;
SELECT create_hypertable('silver.equipment_events', 'ts_event', chunk_time_interval => interval '7 days');
INSERT INTO silver.equipment_events (id_equipment, ts_event, ts_end, status)
SELECT e, t, t + interval '3 minutes', (extract(epoch from t)::int / 600) % 4 FROM generate_series(1, 5) e,
       generate_series(now() - interval '100 days', now() - interval '1 hour', interval '17 minutes') t;
ALTER TABLE silver.equipment_events SET (timescaledb.compress, timescaledb.compress_segmentby = 'id_equipment');
SELECT count(compress_chunk(c)) AS compressed FROM show_chunks('silver.equipment_events', older_than => now() - interval '30 days') c;
CREATE VIEW silver.v_events AS SELECT id_equipment, ts_event, status FROM silver.equipment_events WHERE status <> 3;
GRANT SELECT ON silver.equipment_events TO readapi_ro;
GRANT USAGE ON SCHEMA silver TO lp_writer; GRANT SELECT, INSERT, UPDATE, DELETE ON silver.equipment_events TO lp_writer; GRANT USAGE ON SEQUENCE silver.ev_source_seq TO lp_writer; GRANT SELECT ON silver.v_events TO readapi_ro;
COMMENT ON TABLE silver.equipment_events IS 'events table comment';
COMMENT ON COLUMN silver.equipment_events.status IS 'status column comment';
INSERT INTO ops.retention_policy VALUES ('silver.equipment_events', 'hypertable', 'ts_event', '60 days', now());
-- plc-like: forced RLS + policy
CREATE TABLE silver.plc_link_minutes (id_enterprise int NOT NULL, endpoint text NOT NULL, ts_minute timestamptz NOT NULL, ok_ticks int DEFAULT 0,
  PRIMARY KEY (id_enterprise, endpoint, ts_minute));
SELECT create_hypertable('silver.plc_link_minutes', 'ts_minute', chunk_time_interval => interval '7 days');
ALTER TABLE silver.plc_link_minutes ENABLE ROW LEVEL SECURITY; ALTER TABLE silver.plc_link_minutes FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON silver.plc_link_minutes USING (id_enterprise = current_tenant());
GRANT USAGE ON SCHEMA silver TO tenant_reader; GRANT SELECT ON silver.plc_link_minutes TO tenant_reader;
INSERT INTO silver.plc_link_minutes SELECT ent, 'ep', t, 1 FROM generate_series(1, 2) ent, generate_series(now() - interval '20 days', now(), interval '1 hour') t;
-- bronze-like: immutability trigger
CREATE TABLE bronze.equipment_values_raw (id_equipment int NOT NULL, ts_value timestamptz NOT NULL, source_seq bigint NOT NULL, v real,
  PRIMARY KEY (id_equipment, ts_value, source_seq));
SELECT create_hypertable('bronze.equipment_values_raw', 'ts_value', chunk_time_interval => interval '7 days');
CREATE FUNCTION bronze.no_mutate() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'bronze is immutable'; END $$;
CREATE TRIGGER trg_equipment_values_raw_no_mutate BEFORE DELETE OR UPDATE ON bronze.equipment_values_raw FOR EACH ROW EXECUTE FUNCTION bronze.no_mutate();
INSERT INTO bronze.equipment_values_raw SELECT 1, t, row_number() OVER (), 1 FROM generate_series(now() - interval '20 days', now(), interval '10 minutes') t;
