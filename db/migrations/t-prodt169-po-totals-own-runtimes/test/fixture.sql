-- Minimal shapes of the four relations the view reads + the PRE-migration view (t-operator-replace-runtime with
-- t-no-data-status's NOT IN (6, 20)), security_invoker and a readapi_ro grant like staging.
\set ON_ERROR_STOP 1
DO $$ BEGIN CREATE ROLE readapi_ro; EXCEPTION WHEN duplicate_object THEN NULL; END $$;
CREATE SCHEMA IF NOT EXISTS serving;
CREATE TABLE production_orders (
  id_production_order int PRIMARY KEY, id_equipment int, id_enterprise int, status int,
  ts_start timestamptz, ts_end timestamptz);
CREATE TABLE production_orders_runtime (
  id_production_order_runtime bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_production_order int NOT NULL, id_equipment int, runtime_timerange tstzrange,
  net_production double precision, gross_production double precision);
CREATE TABLE equipment_events (
  id_equipment int NOT NULL, ts_event timestamptz NOT NULL, ts_end timestamptz, duration int, status int,
  forced_creation_system boolean);
CREATE TABLE equipment_values (
  id_equipment int, ts_value timestamptz, net_production_incr real);

CREATE VIEW serving.v_operator_po_details_3 WITH (security_invoker = on) AS
 SELECT base.id_production_order, base.id_equipment, base.id_enterprise, base.net_production, base.scrap,
    base.running_time, base.downtime, base.net_production + base.scrap AS gross,
    ( SELECT r.id_production_order_runtime FROM production_orders_runtime r
       WHERE r.id_production_order = base.id_production_order AND upper(r.runtime_timerange) IS NULL
       ORDER BY (lower(r.runtime_timerange)) DESC LIMIT 1) AS id_production_order_runtime
   FROM ( SELECT po.id_production_order, po.id_equipment, po.id_enterprise, po.ts_start, po.ts_end,
            COALESCE(NULLIF(sum(por.net_production), 0::double precision), (( SELECT COALESCE(sum(ev.net_production_incr), 0::real) AS "coalesce"
                   FROM equipment_values ev
                  WHERE ev.id_equipment = po.id_equipment AND po.ts_start IS NOT NULL AND ev.ts_value >= po.ts_start AND (po.ts_end IS NULL OR ev.ts_value <= po.ts_end)))::double precision, 0::double precision) AS net_production,
            COALESCE(NULLIF(sum(COALESCE(por.gross_production, 0::double precision) - COALESCE(por.net_production, 0::double precision)), 0::double precision), 0::double precision) AS scrap,
            COALESCE(sum(EXTRACT(epoch FROM COALESCE(upper(por.runtime_timerange), now()) - lower(por.runtime_timerange))), 0::numeric)::integer AS running_time,
            COALESCE(( SELECT sum(CASE WHEN ee.ts_end IS NULL THEN GREATEST(0, EXTRACT(epoch FROM now() - ee.ts_event)::integer) ELSE COALESCE(ee.duration, 0) END) AS sum
                   FROM equipment_events ee
                  WHERE ee.id_equipment = po.id_equipment AND po.ts_start IS NOT NULL AND ee.ts_event >= po.ts_start AND (po.ts_end IS NULL OR ee.ts_event <= po.ts_end) AND ee.status NOT IN (6, 20) AND ee.forced_creation_system = false), 0::bigint)::integer AS downtime
           FROM production_orders po
             LEFT JOIN production_orders_runtime por ON por.id_production_order = po.id_production_order
          WHERE po.status = ANY (ARRAY[1, 2, 4])
          GROUP BY po.id_production_order, po.id_equipment, po.id_enterprise, po.ts_start, po.ts_end) base;
GRANT USAGE ON SCHEMA serving TO readapi_ro;
GRANT SELECT ON serving.v_operator_po_details_3 TO readapi_ro;

